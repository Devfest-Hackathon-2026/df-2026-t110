// Command genbuiltins validates a picoheader and generates builtin signatures.
package main

import (
	"bytes"
	json "encoding/json/v2"
	"flag"
	"fmt"
	"go/format"
	"maps"
	"net/url"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"github.com/google/jsonschema-go/jsonschema"
	"gopkg.in/yaml.v3"
)

func main() {
	input := flag.String("input", "../../../../lang/builtins.picoheader.json", "input picoheader")
	schema := flag.String("schema", "../../../../Schema/picolang/header_v0/header.schema.yaml", "header schema")
	output := flag.String("output", "builtins.gen.go", "generated Go file")
	check := flag.Bool("check", false, "check the output without writing")
	flag.Parse()
	if err := run(*input, *schema, *output, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(input, schemaPath, output string, check bool) error {
	data, err := os.ReadFile(input) //nolint:gosec // Input is a local path explicitly chosen by the developer running codegen.
	if err != nil {
		return err
	}
	header, err := validate(data, schemaPath)
	if err != nil {
		return fmt.Errorf("%s: %w", input, err)
	}
	generated, err := render(header)
	if err != nil {
		return err
	}
	if check {
		existing, err := os.ReadFile(output) //nolint:gosec // Output is a local path explicitly chosen by the developer running codegen.
		if err != nil {
			return err
		}
		if !bytes.Equal(existing, generated) {
			return fmt.Errorf("%s is out of date; run mise run generate", output)
		}
		return nil
	}
	return os.WriteFile(output, generated, 0o600)
}

func validate(data []byte, schemaPath string) (map[string]any, error) {
	var value any
	// json/v2 rejects duplicate object names before they can be lost in a map.
	if err := json.Unmarshal(data, &value); err != nil {
		return nil, err
	}
	absolute, err := filepath.Abs(schemaPath)
	if err != nil {
		return nil, err
	}
	root := &url.URL{Scheme: "file", Path: absolute}
	loader := func(uri *url.URL) (*jsonschema.Schema, error) {
		if uri.Scheme != "file" {
			return nil, fmt.Errorf("unsupported schema URI %s", uri)
		}
		raw, err := os.ReadFile(filepath.FromSlash(uri.Path)) //nolint:gosec // References come from the repository's local schema, not network or request data.
		if err != nil {
			return nil, err
		}
		var document any
		if err := yaml.Unmarshal(raw, &document); err != nil {
			return nil, err
		}
		encoded, err := json.Marshal(document)
		if err != nil {
			return nil, err
		}
		var schema jsonschema.Schema
		if err := json.Unmarshal(encoded, &schema); err != nil {
			return nil, err
		}
		return &schema, nil
	}
	schema, err := loader(root)
	if err != nil {
		return nil, err
	}
	resolved, err := schema.Resolve(&jsonschema.ResolveOptions{BaseURI: root.String(), Loader: loader})
	if err != nil {
		return nil, err
	}
	if err := resolved.Validate(value); err != nil {
		return nil, err
	}
	header := value.(map[string]any)
	for _, name := range slices.Sorted(maps.Keys(header)) {
		signature := header[name].(map[string]any)
		parameters := make(map[string]struct{})
		if declared, ok := signature["typeParameters"].([]any); ok {
			for _, parameter := range declared {
				parameters[parameter.(string)] = struct{}{}
			}
		}
		var visit func(any) error
		visit = func(typ any) error {
			if compound, ok := typ.(map[string]any); ok {
				if compound["kind"] == "type_parameter" {
					if _, declared := parameters[compound["name"].(string)]; !declared {
						return fmt.Errorf("%s: undeclared type parameter %q", name, compound["name"])
					}
				} else {
					return visit(compound["elementType"])
				}
			}
			return nil
		}
		for _, param := range signature["params"].([]any) {
			if err := visit(param); err != nil {
				return nil, err
			}
		}
		if err := visit(signature["returnType"]); err != nil {
			return nil, err
		}
	}
	return header, nil
}

func render(header map[string]any) ([]byte, error) {
	var code strings.Builder
	code.WriteString("// Code generated by genbuiltins from lang/builtins.picoheader.json; DO NOT EDIT.\n\npackage picolangbot\n\n")
	code.WriteString("// BuiltinSignatures returns an independent signature table for the builtins.\nfunc BuiltinSignatures() map[Name]Signature {\nreturn map[Name]Signature{\n")
	for _, name := range slices.Sorted(maps.Keys(header)) {
		signature := header[name].(map[string]any)
		fmt.Fprintf(&code, "%s: {Params: []Type{", strconv.Quote(name))
		for _, param := range signature["params"].([]any) {
			code.WriteString(goType(param) + ",")
		}
		fmt.Fprintf(&code, "}, Result: %s},\n", goType(signature["returnType"]))
	}
	code.WriteString("}\n}\n")
	return format.Source([]byte(code.String()))
}

func goType(typ any) string {
	if primitive, ok := typ.(string); ok {
		return map[string]string{
			"bool": "BoolType{}", "integer": "IntegerType{}", "unit": "UnitType{}",
			"terrain": "TerrainType{}", "rotation": "RotationType{}", "distance_target": "DistanceTargetType{}",
		}[primitive]
	}
	compound := typ.(map[string]any)
	if compound["kind"] == "type_parameter" {
		return "typeParameter{Name: " + strconv.Quote(compound["name"].(string)) + "}"
	}
	constructor := "StackType"
	if compound["kind"] == "option" {
		constructor = "OptionType"
	}
	return constructor + "{ElementType: " + goType(compound["elementType"]) + "}"
}
